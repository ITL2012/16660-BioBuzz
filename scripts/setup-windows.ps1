# =============================================================================
# setup-windows.ps1 — one-command project setup on Windows
#
#   powershell -ExecutionPolicy Bypass -File scripts\setup-windows.ps1
#
# If PowerShell blocks the script, run it from the project folder with:
#   powershell -ExecutionPolicy Bypass -File .\scripts\setup-windows.ps1
#
# See the manual (Chapter 3) for what each step does and how to fix any
# error by hand. Safe to run more than once.
# =============================================================================

$ErrorActionPreference = "Stop"

function Say  { Write-Host "==> $args" -ForegroundColor Cyan }
function Ok   { Write-Host "  OK   $args" -ForegroundColor Green }
function Warn { Write-Host "  WARN $args" -ForegroundColor Yellow }
function Die  { Write-Host "  ERROR $args" -ForegroundColor Red; exit 1 }

Write-Host "======================================================================"
Write-Host " BioBuzz project setup (Windows)"
Write-Host "======================================================================"

$ProjectDir = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $ProjectDir

# ---------------------------------------------------------------- 1. JDK
Say "Checking Java..."
$java = Get-Command java -ErrorAction SilentlyContinue
if (-not $java) {
    Die "Java not found. Install a JDK 17+ (Temurin/Oracle) and re-run, or set JAVA_HOME."
}
$javaVersionRaw = (& java -version 2>&1 | Select-Object -First 1) -join ""
if ($javaVersionRaw -match 'version "(\d+)') {
    $javaMajor = [int]$Matches[1]
} else {
    $javaMajor = 0
}
if ($javaMajor -lt 17) {
    Die "JDK 17+ required, found: $javaVersionRaw"
}
Ok $javaVersionRaw

if ($env:JAVA_HOME) {
    Ok "JAVA_HOME=$env:JAVA_HOME"
} else {
    Warn "JAVA_HOME is not set. Android Studio usually sets it. If the build complains about the JDK, set JAVA_HOME to your JDK 17 folder."
}

# ------------------------------------------------------- 2. Android SDK
Say "Locating the Android SDK..."
$SdkDir = $env:ANDROID_HOME
if (-not $SdkDir) { $SdkDir = $env:ANDROID_SDK_ROOT }

if (-not $SdkDir) {
    $candidates = @(
        "$env:LOCALAPPDATA\Android\Sdk",
        "$env:USERPROFILE\AppData\Local\Android\Sdk",
        "C:\Android\Sdk"
    )
    foreach ($c in $candidates) {
        if (Test-Path $c) { $SdkDir = $c; break }
    }
}

if (-not $SdkDir -and (Test-Path "local.properties")) {
    $line = Select-String -Path "local.properties" -Pattern '^sdk\.dir=(.*)$' | Select-Object -First 1
    if ($line) { $SdkDir = $line.Matches[0].Groups[1].Value -replace '\\:', ':' }
}

if (-not $SdkDir -or -not (Test-Path $SdkDir)) {
    Warn "Android SDK not found automatically."
    Write-Host ""
    Write-Host "  Install it with one of:"
    Write-Host "    winget install Google.AndroidStudio   (then use the SDK Manager)"
    Write-Host "    OR download command-line tools from"
    Write-Host "       https://developer.android.com/studio#command-line-tools-only"
    Write-Host ""
    $SdkDir = Read-Host "  Path to your Android SDK (blank to quit)"
    if (-not $SdkDir) { Die "No SDK path given." }
}

# Normalize to forward slashes, which Gradle prefers.
$SdkDir = $SdkDir -replace '\\', '/'
Ok "Android SDK: $SdkDir"

# --------------------------------------------------------- 3. local.properties
Say "Writing local.properties..."
# On Windows a colon in the path must be escaped for Java properties.
$escaped = $SdkDir -replace ':', '\:'
"# Generated by scripts/setup-windows.ps1 - do not commit this file." | Out-File -Encoding utf8 "local.properties"
"sdk.dir=$escaped" | Out-File -Encoding utf8 -Append "local.properties"
Ok "local.properties -> sdk.dir=$escaped"

# ------------------------------------------------------------- 4. adb
Say "Checking adb..."
$adb = Join-Path $SdkDir "platform-tools/adb.exe"
if (Test-Path $adb) {
    Ok "adb found: $adb"
    & $adb devices -l 2>$null | ForEach-Object { Write-Host "    $_" }
} else {
    Warn "adb not found at $adb (the Control Hub USB tools). Install 'Android SDK Platform-Tools'."
}

# ------------------------------------------------------ 5. SDK components
Say "Checking required SDK components..."
$sdkmanager = Join-Path $SdkDir "cmdline-tools/latest/bin/sdkmanager.bat"
if (Test-Path $sdkmanager) {
    Ok "sdkmanager found"
} else {
    Warn "sdkmanager not found — open Android Studio > SDK Manager and install:"
    Warn "    Android SDK Platform 30, Android SDK Build-Tools 30.0.3, Platform-Tools"
}

# ------------------------------------------------------ 6. build + test
Say "Building and running unit tests (first build downloads dependencies, be patient)..."
& "$ProjectDir\gradlew.bat" :TeamCode:assembleDebug :TeamCode:test --console=plain
if ($LASTEXITCODE -ne 0) { Die "Build failed. Scroll up for the first error." }
Ok "Build succeeded, tests passed"

Write-Host ""
Write-Host "======================================================================"
Write-Host " SETUP COMPLETE"
Write-Host "======================================================================"
Write-Host "Next steps:"
Write-Host "  1. Open the project in Android Studio (File > Open > this folder)."
Write-Host "  2. Plug the Control Hub into this PC with a USB-C data cable."
Write-Host "  3. Run:  powershell -ExecutionPolicy Bypass -File scripts\deploy_to_hub.ps1"
Write-Host "  4. On the robot, run the 'PRE-FLIGHT CHECK' OpMode."
Write-Host ""
