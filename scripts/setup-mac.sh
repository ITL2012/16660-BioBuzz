#!/usr/bin/env bash
# =============================================================================
# setup-mac.sh — one-command project setup on macOS
#
#   bash scripts/setup-mac.sh
#
# What it does:
#   1. Checks for the tools the build needs (JDK, Android SDK)
#   2. Creates local.properties with YOUR SDK path (the #1 cause of
#      "works on my computer only" — local.properties is gitignored)
#   3. Verifies the JDK version is new enough
#   4. Builds the app and runs the unit tests
#
# Safe to run more than once. It never installs anything system-wide without
# telling you first.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
say()  { echo -e "${BLUE}==>${NC} $*"; }
ok()   { echo -e "${GREEN}  OK${NC} $*"; }
warn() { echo -e "${YELLOW}  WARN${NC} $*"; }
die()  { echo -e "${RED}  ERROR${NC} $*" >&2; exit 1; }

echo "======================================================================"
echo " BioBuzz project setup (macOS)"
echo "======================================================================"

# ---------------------------------------------------------------- 1. JDK
say "Checking Java..."
if ! command -v java >/dev/null 2>&1; then
    die "Java not found. Install a JDK 17+ (see Chapter 3 of the manual)."
fi
JAVA_VERSION_RAW="$(java -version 2>&1 | head -1)"
JAVA_MAJOR="$(echo "$JAVA_VERSION_RAW" | sed -E 's/.*version "([0-9]+).*/\1/')"
if [ -z "$JAVA_MAJOR" ] || [ "$JAVA_MAJOR" -lt 17 ]; then
    die "JDK 17+ required, found: $JAVA_VERSION_RAW"
fi
ok "$JAVA_VERSION_RAW"

# Tell Gradle which JDK to use, so Android Studio and the CLI agree.
JAVA_HOME_REAL="$(/usr/libexec/java_home -v 17 2>/dev/null || /usr/libexec/java_home 2>/dev/null || true)"
if [ -n "$JAVA_HOME_REAL" ]; then
    export JAVA_HOME="$JAVA_HOME_REAL"
    ok "JAVA_HOME=$JAVA_HOME"
fi

# ------------------------------------------------------- 2. Android SDK
say "Locating the Android SDK..."
SDK_DIR=""
for candidate in \
    "$HOME/Library/Android/sdk" \
    "$HOME/Android/Sdk" \
    "/usr/local/share/android-sdk" \
    "/opt/android-sdk"; do
    if [ -d "$candidate" ]; then SDK_DIR="$candidate"; break; fi
done

if [ -z "$SDK_DIR" ] && [ -f local.properties ]; then
    SDK_DIR="$(sed -n 's/^sdk\.dir=//p' local.properties | head -1)"
    SDK_DIR="${SDK_DIR//\\:/:}"
fi

if [ -z "$SDK_DIR" ] || [ ! -d "$SDK_DIR" ]; then
    warn "Android SDK not found automatically."
    echo ""
    echo "  Install it with one of:"
    echo "    brew install --cask android-commandlinetools   # then use sdkmanager"
    echo "    OR download Android Studio from https://developer.android.com/studio"
    echo ""
    read -r -p "  Path to your Android SDK (blank to quit): " SDK_DIR
    [ -n "$SDK_DIR" ] || die "No SDK path given. Install Android Studio and re-run."
    mkdir -p "$SDK_DIR" 2>/dev/null || true
fi
ok "Android SDK: $SDK_DIR"

# --------------------------------------------------------- 3. local.properties
say "Writing local.properties..."
# The ':' must be escaped for Java properties on Windows-style paths; on macOS
# a plain path is fine, but escape anyway for safety.
ESCAPED_SDK="${SDK_DIR//:/\\:}"
printf '# Generated by scripts/setup-mac.sh — do not commit this file.\nsdk.dir=%s\n' "$ESCAPED_SDK" > local.properties
ok "local.properties -> sdk.dir=$ESCAPED_SDK"

# ------------------------------------------------------------- 4. adb
say "Checking adb..."
ADB="$SDK_DIR/platform-tools/adb"
if [ -x "$ADB" ]; then
    ok "adb found: $ADB"
    chmod +x "$ADB" 2>/dev/null || true
    "$ADB" devices -l 2>/dev/null | sed 's/^/    /' || true
else
    warn "adb not found at $ADB (the Control Hub USB tools). Install the SDK Platform-Tools."
fi

# ------------------------------------------------- 5. SDK components
say "Checking required SDK components..."
SDKMANAGER="$SDK_DIR/cmdline-tools/latest/bin/sdkmanager"
if [ -x "$SDKMANAGER" ]; then
    ok "sdkmanager found"
    "$SDKMANAGER" --list_installed 2>/dev/null | grep -q "platforms;android-30" \
        && ok "platforms;android-30 installed" \
        || warn "platforms;android-30 may be missing — run: $SDKMANAGER 'platforms;android-30'"
else
    warn "sdkmanager not found — open Android Studio > SDK Manager and install:"
    warn "    Android SDK Platform 30, Android SDK Build-Tools 30.0.3, Platform-Tools"
fi

# ------------------------------------------------------ 6. build + test
say "Building and running unit tests (first build downloads dependencies, be patient)..."
if [ ! -x ./gradlew ]; then
    chmod +x ./gradlew 2>/dev/null || true
fi
./gradlew :TeamCode:assembleDebug :TeamCode:test --console=plain
ok "Build succeeded, tests passed"

echo ""
echo "======================================================================"
echo -e "${GREEN} SETUP COMPLETE${NC}"
echo "======================================================================"
echo "Next steps:"
echo "  1. Open the project in Android Studio (File > Open > this folder)."
echo "  2. Plug the Control Hub into this Mac with a USB-C data cable."
echo "  3. Run:  bash scripts/deploy_to_hub.sh"
echo "  4. On the robot, run the 'PRE-FLIGHT CHECK' OpMode."
echo ""
