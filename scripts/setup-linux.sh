#!/usr/bin/env bash
# =============================================================================
# setup-linux.sh — one-command project setup on Linux
#
#   bash scripts/setup-linux.sh
#
# See the manual (Chapter 3) for what each step does and how to fix any
# error by hand. Safe to run more than once.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
say()  { echo -e "${BLUE}==>${NC} $*"; }
ok()   { echo -e "${GREEN}  OK${NC} $*"; }
warn() { echo -e "${YELLOW}  WARN${NC} $*"; }
die()  { echo -e "${RED}  ERROR${NC} $*" >&2; exit 1; }

echo "======================================================================"
echo " BioBuzz project setup (Linux)"
echo "======================================================================"

# ---------------------------------------------------------------- 1. JDK
say "Checking Java..."
if ! command -v java >/dev/null 2>&1; then
    die "Java not found. Install a JDK 17+:
    sudo apt install openjdk-17-jdk   (Debian/Ubuntu)
    sudo dnf install java-17-openjdk-devel   (Fedora)"
fi
JAVA_VERSION_RAW="$(java -version 2>&1 | head -1)"
JAVA_MAJOR="$(echo "$JAVA_VERSION_RAW" | sed -E 's/.*version "([0-9]+).*/\1/')"
if [ -z "$JAVA_MAJOR" ] || [ "$JAVA_MAJOR" -lt 17 ]; then
    die "JDK 17+ required, found: $JAVA_VERSION_RAW"
fi
ok "$JAVA_VERSION_RAW"

# ------------------------------------------------------- 2. Android SDK
say "Locating the Android SDK..."
SDK_DIR="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK_DIR" ]; then
    for candidate in "$HOME/Android/Sdk" "$HOME/android-sdk" "/opt/android-sdk" "/usr/lib/android-sdk"; do
        if [ -d "$candidate" ]; then SDK_DIR="$candidate"; break; fi
    done
fi
if [ -z "$SDK_DIR" ] && [ -f local.properties ]; then
    SDK_DIR="$(sed -n 's/^sdk\.dir=//p' local.properties | head -1)"
    SDK_DIR="${SDK_DIR//\\:/:}"
fi

if [ -z "$SDK_DIR" ] || [ ! -d "$SDK_DIR" ]; then
    warn "Android SDK not found automatically."
    echo ""
    echo "  Install it with one of:"
    echo "    sudo apt install android-sdk    # may be outdated"
    echo "    OR download command-line tools from"
    echo "       https://developer.android.com/studio#command-line-tools-only"
    echo ""
    read -r -p "  Path to your Android SDK (blank to quit): " SDK_DIR
    [ -n "$SDK_DIR" ] || die "No SDK path given."
    mkdir -p "$SDK_DIR" 2>/dev/null || true
fi
ok "Android SDK: $SDK_DIR"

# --------------------------------------------------------- 3. local.properties
say "Writing local.properties..."
ESCAPED_SDK="${SDK_DIR//:/\\:}"
printf '# Generated by scripts/setup-linux.sh — do not commit this file.\nsdk.dir=%s\n' "$ESCAPED_SDK" > local.properties
ok "local.properties -> sdk.dir=$ESCAPED_SDK"

# ------------------------------------------------------------- 4. udev rules
say "Checking USB permissions for the Control Hub..."
if [ ! -f /etc/udev/rules.d/99-ftc.rules ] && [ ! -f /etc/udev/rules.d/51-android.rules ]; then
    warn "No Android USB rules found. Without them, adb may not see the Control Hub."
    echo "    Create /etc/udev/rules.d/99-ftc.rules containing:"
    echo "      SUBSYSTEM==\"usb\", ATTR{idVendor}==\"18d1\", MODE=\"0666\""
    echo "    then: sudo udevadm control --reload-rules && sudo udevadm trigger"
fi

# ------------------------------------------------------------- 5. adb
say "Checking adb..."
ADB="$SDK_DIR/platform-tools/adb"
if [ -x "$ADB" ]; then
    ok "adb found: $ADB"
    "$ADB" devices -l 2>/dev/null | sed 's/^/    /' || true
else
    warn "adb not found at $ADB (the Control Hub USB tools)."
fi

# ------------------------------------------------------ 6. SDK components
say "Checking required SDK components..."
SDKMANAGER="$SDK_DIR/cmdline-tools/latest/bin/sdkmanager"
if [ -x "$SDKMANAGER" ]; then
    ok "sdkmanager found"
    "$SDKMANAGER" --list_installed 2>/dev/null | grep -q "platforms;android-30" \
        && ok "platforms;android-30 installed" \
        || warn "platforms;android-30 may be missing — run: $SDKMANAGER 'platforms;android-30'"
else
    warn "sdkmanager not found — install Android SDK Platform 30 and Platform-Tools."
fi

# ------------------------------------------------------ 7. build + test
say "Building and running unit tests (first build downloads dependencies, be patient)..."
[ -x ./gradlew ] || chmod +x ./gradlew 2>/dev/null || true
./gradlew :TeamCode:assembleDebug :TeamCode:test --console=plain
ok "Build succeeded, tests passed"

echo ""
echo "======================================================================"
echo -e "${GREEN} SETUP COMPLETE${NC}"
echo "======================================================================"
echo "Next steps:"
echo "  1. Open the project in Android Studio (File > Open > this folder)."
echo "  2. Plug the Control Hub into this Linux box with a USB-C data cable."
echo "  3. Run:  bash scripts/deploy_to_hub.sh"
echo "  4. On the robot, run the 'PRE-FLIGHT CHECK' OpMode."
echo ""
